// 위도·경도 좌표로 클릭한 국가 자동 판별 (정확한 경계 박스 우선 -> 최근접 국가 폴백)
window.HistoryData.findCountryByLatLng = function (lat, lng) {
  const list = window.HistoryData.countries || [];
  // 1단계: 경계 박스(bounds)에 포함되는 국가 후보 수집 후 중심점 가장 가까운 국가 선택
  const inside = list.filter(c => {
    const [minLat, maxLat, minLng, maxLng] = c.bounds;
    return lat >= minLat && lat <= maxLat && lng >= minLng && lng <= maxLng;
  });

  const pool = inside.length ? inside : list;
  let best = null;
  let bestDist = Infinity;
  pool.forEach(c => {
    const dLat = lat - c.center.lat;
    const dLng = lng - c.center.lng;
    const dist = dLat * dLat + dLng * dLng;
    if (dist < bestDist) {
      bestDist = dist;
      best = c;
    }
  });
  return best;
};
