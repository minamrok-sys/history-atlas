// countries 배열에 iso2, isoIds, 컬러 국기 HTML 헬퍼 자동 주입
(function enrichCountries() {
  const countries = window.HistoryData.countries || [];
  const meta = window.HistoryData.countryGeoMeta;
  countries.forEach(c => {
    const m = meta[c.id];
    if (m) {
      c.iso2 = m.iso2;
      c.isoIds = m.isoIds;
      c.flagImg = `<img class="flag-icon" src="https://flagcdn.com/w40/${m.iso2}.png" alt="${c.name}" loading="lazy" />`;
    } else {
      c.flagImg = `<span>${c.flag || '🌍'}</span>`;
    }
  });
})();
